# Los operadores lpogicos y de comparación son fundamentales en la programación, ya que permiten evaluar condiciones y tomar decisiones basadas en ellas
#  AND(&) es para evaluar si ambas condiciones son verdaderas
resultado = True & True  # resultado es True
resultado1 = True & False  # resultado es False
resultado2 = False & True  # resultado es False      
resultado3 = False & False  # resultado es False

# OR(|) es para evaluar si al menos una de las condiciones es verdadera
resultado4 = True | True  # resultado es True
resultado5 = False | True  # resultado es True
resultado6 = True | False  # resultado es True
resultado7 = False | False  # resultado es False

# NOT(not) es para invertir el valor de una condición
resultado8 = not True  # resultado es False
resultado9 = not False  # resultado es True

print(resultado)



